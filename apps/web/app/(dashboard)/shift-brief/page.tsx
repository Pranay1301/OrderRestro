"use client";

/**
 * Shift Brief page (OWN ADDITION, not upstream).
 *
 * Shows a deterministic, template-generated brief of the day's numbers
 * and a fixed-shape Q&A box. The UI says plainly that no AI model is
 * involved - the backend labels every payload it returns.
 */
import { useQuery } from "@tanstack/react-query";
import { Sparkles, Send } from "lucide-react";
import { useState } from "react";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Skeleton } from "@/components/ui/skeleton";
import { useBranch } from "@/hooks/use-branch";
import { api } from "@/lib/api";

interface BriefSection {
  heading: string;
  lines: string[];
}
interface ShiftBrief {
  title: string;
  generatedAt: string;
  generator: string;
  sections: BriefSection[];
}
interface QaAnswer {
  question: string;
  answer: string;
  matched: boolean;
  knownShapes?: string[];
  parser: string;
  generator: string;
}

const SUGGESTIONS = [
  "what sold best today?",
  "revenue today",
  "how many orders today?",
  "when were we busiest?",
  "online vs offline orders",
  "how much did we waste today?",
];

export default function ShiftBriefPage() {
  const { branchId } = useBranch();
  const [question, setQuestion] = useState("");
  const [history, setHistory] = useState<QaAnswer[]>([]);
  const [asking, setAsking] = useState(false);

  const { data: brief, isLoading } = useQuery({
    queryKey: ["shift-brief", branchId],
    queryFn: () => api.get<ShiftBrief>(`/shift-brief/today?branchId=${branchId}`),
    enabled: !!branchId,
  });

  async function ask(q: string) {
    if (!q.trim() || !branchId) return;
    setAsking(true);
    try {
      const res = await api.post<QaAnswer>("/shift-brief/ask", {
        branchId,
        question: q.trim(),
      });
      setHistory((h) => [res, ...h]);
      setQuestion("");
    } finally {
      setAsking(false);
    }
  }

  return (
    <div className="mx-auto max-w-3xl space-y-6 p-6">
      <div>
        <h1 className="flex items-center gap-2 text-2xl font-semibold">
          <Sparkles className="h-6 w-6" /> Shift Brief
        </h1>
        <p className="mt-1 text-sm text-muted-foreground">
          Your day, summed up from the POS data. Generated by fixed
          templates and a keyword parser -{" "}
          <strong>no AI model is involved</strong>, so every number traces
          to a database query.
        </p>
      </div>

      {isLoading || !brief ? (
        <Skeleton className="h-64 w-full" />
      ) : (
        <Card className="space-y-5 p-5">
          <div className="flex items-baseline justify-between">
            <h2 className="text-lg font-medium">{brief.title}</h2>
            <span className="text-xs text-muted-foreground">
              {new Date(brief.generatedAt).toLocaleTimeString()}
            </span>
          </div>
          {brief.sections.map((s) => (
            <div key={s.heading}>
              <h3 className="text-sm font-semibold uppercase tracking-wide text-muted-foreground">
                {s.heading}
              </h3>
              <ul className="mt-1 list-disc space-y-1 pl-5 text-sm">
                {s.lines.map((line, i) => (
                  <li key={i}>{line}</li>
                ))}
              </ul>
            </div>
          ))}
          <p className="border-t pt-3 text-xs text-muted-foreground">
            Generator: {brief.generator}
          </p>
        </Card>
      )}

      <Card className="space-y-4 p-5">
        <h2 className="text-lg font-medium">Ask about the numbers</h2>
        <div className="flex gap-2">
          <Input
            value={question}
            onChange={(e) => setQuestion(e.target.value)}
            onKeyDown={(e) => e.key === "Enter" && ask(question)}
            placeholder="e.g. what sold best today?"
          />
          <Button onClick={() => ask(question)} disabled={asking}>
            <Send className="h-4 w-4" />
          </Button>
        </div>
        <div className="flex flex-wrap gap-2">
          {SUGGESTIONS.map((s) => (
            <button
              key={s}
              onClick={() => ask(s)}
              className="rounded-full border px-3 py-1 text-xs text-muted-foreground hover:bg-accent"
            >
              {s}
            </button>
          ))}
        </div>
        {history.map((h, i) => (
          <div key={i} className="rounded-md border p-3 text-sm">
            <p className="font-medium">{h.question}</p>
            <p className="mt-1">{h.answer}</p>
            {!h.matched && h.knownShapes && (
              <ul className="mt-1 list-disc pl-5 text-xs text-muted-foreground">
                {h.knownShapes.map((k) => (
                  <li key={k}>{k}</li>
                ))}
              </ul>
            )}
            <p className="mt-1 text-xs text-muted-foreground">
              Parser: {h.parser}
            </p>
          </div>
        ))}
      </Card>
    </div>
  );
}
